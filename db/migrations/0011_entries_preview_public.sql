-- Витрина до гейта: флаг «эту статью можно показать неподписанному».
-- Применить вручную ДО sync_content.py:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/migrations/0011_entries_preview_public.sql
-- Идемпотентно.
--
-- Зачем. GateScreen показывал неподписанному три числа и кнопку «Подписаться» —
-- ни строчки контента. Подписку просили авансом, а весь трафик с конкретных постов
-- канала (deep link entry_{slug}) упирался в одинаковую заглушку: человек шёл
-- за названной статьёй и не видел её.
--
-- Механика намеренно консервативная: DEFAULT false, то есть по умолчанию наружу
-- не открыто НИЧЕГО. Статья становится публичной, только если в её frontmatter
-- явно стоит `preview: true` — решение живёт в контент-файле и едет обычным
-- пайплайном, как всё остальное в этом проекте. Случайно открыть каталог целиком
-- нельзя: для этого пришлось бы проставить флаг в 197 файлах.
--
-- Гейт эта миграция не трогает: require_subscribed остаётся на всех ручках,
-- кроме новой /api/public/*, которая умеет отдавать только помеченные строки.

ALTER TABLE baza.entries ADD COLUMN IF NOT EXISTS preview_public BOOLEAN NOT NULL DEFAULT false;

-- Частичный индекс: строк с флагом единицы, полный индекс по булеву полю бесполезен.
CREATE INDEX IF NOT EXISTS idx_entries_preview_public
    ON baza.entries (slug) WHERE preview_public AND published;
