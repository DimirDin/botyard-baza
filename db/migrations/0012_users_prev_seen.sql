-- «Что нового с прошлого захода»: предыдущий визит пользователя.
-- Применить вручную ДО перезапуска бэкенда:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/migrations/0012_users_prev_seen.sql
-- Идемпотентно.
--
-- Зачем отдельная колонка, а не last_seen. Гейт обновляет last_seen на now()
-- в том же запросе, которым проверяет подписку, — то есть к моменту, когда
-- главная считает «что нового», last_seen уже равен текущему визиту и разница
-- всегда пустая. prev_seen хранит отметку ПРЕДЫДУЩЕГО захода.
--
-- NULL означает «первый визит»: для такого пользователя ничего не показываем,
-- иначе новичок увидел бы «197 новых статей», что бессмысленно.
--
-- Частота обновления. Запись идёт только при промахе кэша подписки в Redis
-- (TTL 6 ч для подписанных), поэтому prev_seen сдвигается не чаще раза в 6 часов.
-- Это желаемое поведение: плашка не обнуляется от того, что человек закрыл
-- и снова открыл приложение через минуту.

ALTER TABLE baza.users ADD COLUMN IF NOT EXISTS prev_seen TIMESTAMPTZ;
